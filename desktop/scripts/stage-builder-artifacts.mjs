import fs from 'node:fs';
import path from 'node:path';
import { desktop,release,version } from './release-tools.mjs';
const platform=process.argv[2];
if(!['mac','windows'].includes(platform)) throw new Error('Expected mac or windows');
const source=path.join(desktop,'dist','builder-release');
const metadata=platform==='mac'?'latest-mac.yml':'latest.yml';
const names=fs.readdirSync(source).filter((name)=>name===metadata || (name.startsWith('mystocktracer-v'+version+'-'+(platform==='mac'?'macos':'windows')+'-') && /\.(zip|exe)(\.blockmap)?$/.test(name)));
if(!names.includes(metadata)) throw new Error('Missing updater metadata');
fs.mkdirSync(release,{recursive:true});
for(const name of names) fs.copyFileSync(path.join(source,name),path.join(release,name));
console.log('Staged '+names.length+' '+platform+' artifacts without deleting previous releases');