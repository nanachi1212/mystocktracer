import fs from 'node:fs';
import path from 'node:path';
import { desktop,arch,version,release,run } from './release-tools.mjs';
import { verifyReleasePackage } from './verify-release-package.mjs';
if(!['x64','arm64'].includes(arch)) throw new Error('Unsupported Windows architecture');
const source=path.join(desktop,'dist','builder-release','win-unpacked');
verifyReleasePackage(source,'windows');
fs.mkdirSync(release,{recursive:true});
const destination=path.join(release,`mystocktracer-v${version}-windows-${arch}.zip`);
run('powershell.exe',['-NoProfile','-NonInteractive','-Command',"$ErrorActionPreference = 'Stop'; Compress-Archive -LiteralPath $env:MYSTOCKTRACER_ARCHIVE_SOURCE -DestinationPath $env:MYSTOCKTRACER_ARCHIVE_DESTINATION -CompressionLevel Optimal -Force"],{env:{...process.env,MYSTOCKTRACER_ARCHIVE_SOURCE:source,MYSTOCKTRACER_ARCHIVE_DESTINATION:destination}});
console.log('Created '+destination);